"""
Generate docs/evidence/security-test-report.md from a real test run.

    cd backend && python scripts/security_evidence.py

Runs pytest (with coverage), ruff, bandit and pip-audit, then groups every
test under the security control it provides evidence for. The report records
the commit, date and tool versions so a reviewer can reproduce it.
"""

import datetime as dt
import platform
import re
import subprocess  # nosec
import sys
import tempfile
import xml.etree.ElementTree as ET  # nosec
from collections import defaultdict
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
REPORT = BACKEND.parent / "docs" / "evidence" / "security-test-report.md"

# Controls from the internship task list, mapped to the register (SC-xx)
CONTROLS = {
    "AUTH": "Secure authentication (SC-01)",
    "HASH": "Password hashing and policy (SC-01)",
    "RBAC": "Authorization: directional consent, IDOR, RBAC (SC-02, SC-03)",
    "INPUT": "Input validation and safe errors (SC-04)",
    "SESSION": "JWT / session handling, CSRF, headers (SC-05)",
    "RATE": "API rate limiting and lockout (SC-01, SC-04)",
    "AUDIT": "Security audit logging (SC-04, SC-08)",
    "SAFETY": "Freshness, battery and check-in safety (SC-07)",
    "CONFIG": "Secure configuration and data protection (SC-06)",
}

MODULE_DEFAULT = {
    "test_auth": "SESSION",
    "test_rate_limit": "RATE",
    "test_social": "RBAC",
    "test_location_shares": "RBAC",
    "test_locations": "RBAC",
    "test_checkins": "SAFETY",
    "test_admin": "RBAC",
    "test_authz_audit": "AUDIT",
    "test_core": "CONFIG",
    "test_web_client": "SESSION",
    "test_security_attacks": "INPUT",
}

# First matching keyword wins (checked against "module::test_name")
KEYWORD_RULES = [
    (r"argon2|weak_password|password_change_enforces|policy|cli_creates_admin", "HASH"),
    (r"lock|rate_limit|rate_limited|redis|limiter|per_user_limit", "RATE"),
    (r"audit", "AUDIT"),
    (r"register|login|wrong_password|unknown_user|sc01", "AUTH"),
    (r"freshness|battery|stale|dead|navigation|out_of_order", "SAFETY"),
    (
        r"idor|sc02|foreign|third_party|admin|role|cannot|only_owner|one_way|revoke|expired|block",
        "RBAC",
    ),
    (r"sc05|csrf|cookie|token|session|logout|header|csp|xss|html", "SESSION"),
    (r"sc04|validation|invalid|injection|unknown_fields|oversized|malformed|problem", "INPUT"),
    (r"production|settings", "CONFIG"),
]


def run(cmd: list[str]) -> subprocess.CompletedProcess:
    # Fixed local developer tools only, never user input
    return subprocess.run(cmd, cwd=BACKEND, capture_output=True, text=True)  # noqa: S603  # nosec


def classify(module: str, name: str) -> str:
    key = f"{module}::{name}"
    for pattern, control in KEYWORD_RULES:
        if re.search(pattern, key):
            return control
    return MODULE_DEFAULT.get(module, "INPUT")


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        junit = Path(tmp) / "junit.xml"
        tests = run(
            [
                sys.executable,
                "-m",
                "pytest",
                "-p",
                "no:warnings",
                f"--junitxml={junit}",
                "--cov=app",
                "--cov-report=term",
            ]
        )
        root = ET.parse(junit).getroot()  # noqa: S314  # nosec  (our own pytest output)

    results: dict[str, list[tuple[str, str]]] = defaultdict(list)
    totals = {"passed": 0, "failed": 0, "skipped": 0}
    for case in root.iter("testcase"):
        module = case.get("classname", "").split(".")[-1]
        name = case.get("name", "")
        if case.find("failure") is not None or case.find("error") is not None:
            outcome = "FAIL"
            totals["failed"] += 1
        elif case.find("skipped") is not None:
            outcome = "skipped"
            totals["skipped"] += 1
        else:
            outcome = "pass"
            totals["passed"] += 1
        results[classify(module, name)].append((f"{module}::{name}", outcome))

    coverage = re.search(r"^TOTAL\s+\d+\s+\d+\s+(\d+%)", tests.stdout, re.MULTILINE)
    ruff = run([sys.executable, "-m", "ruff", "check", "."])
    bandit = run([sys.executable, "-m", "bandit", "-q", "-c", "pyproject.toml", "-r", "app"])
    audit = run([sys.executable, "-m", "pip_audit", "-r", "requirements.txt"])
    commit = run(["git", "rev-parse", "--short", "HEAD"]).stdout.strip() or "unknown"
    dirty = bool(run(["git", "status", "--porcelain", "--", "app", "tests"]).stdout.strip())

    lines = [
        "# Security Test Report",
        "",
        "Generated by `backend/scripts/security_evidence.py` from a real run. To reproduce:",
        "`cd backend && pip install -r requirements-dev.txt`, then",
        "`python scripts/security_evidence.py`.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Date (UTC) | {dt.datetime.now(dt.UTC):%Y-%m-%d %H:%M} |",
        f"| Commit | `{commit}`{' (with uncommitted changes)' if dirty else ''} |",
        f"| Python | {platform.python_version()} |",
        f"| Tests | {totals['passed']} passed, {totals['failed']} failed, "
        f"{totals['skipped']} skipped |",
        f"| Line coverage (app/) | {coverage.group(1) if coverage else 'n/a'} |",
        f"| Lint (ruff) | {'clean' if ruff.returncode == 0 else 'FINDINGS'} |",
        f"| Static analysis (bandit) | {'no findings' if bandit.returncode == 0 else 'FINDINGS'} |",
        "| Dependency audit (pip-audit) | "
        + ("no known vulnerabilities |" if audit.returncode == 0 else "VULNERABILITIES FOUND |"),
        "",
        "Test database: in-memory SQLite (unit/integration). PostgreSQL-specific controls",
        "(runtime role privileges, migrations) are evidenced in",
        "[database-least-privilege.md](./database-least-privilege.md) and by the CI migration job.",
        "",
    ]
    for key, title in CONTROLS.items():
        rows = sorted(results.get(key, []))
        if not rows:
            continue
        passed = sum(1 for _, outcome in rows if outcome == "pass")
        lines += [
            f"## {title}",
            "",
            f"{passed}/{len(rows)} passing.",
            "",
            "| Test | Result |",
            "|---|---|",
        ]
        lines += [f"| `{name}` | {outcome} |" for name, outcome in rows]
        lines.append("")

    if audit.returncode != 0 or bandit.returncode != 0:
        lines += [
            "## Tool findings",
            "",
            "```",
            bandit.stdout[-3000:],
            audit.stdout[-3000:],
            "```",
            "",
        ]

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines))
    print(f"Wrote {REPORT} ({totals['passed']} passed, {totals['failed']} failed)")
    return 0 if totals["failed"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
