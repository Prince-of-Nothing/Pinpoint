/// Local trust state for a peer's safety number. It is a user record on this
/// device, not a cryptographic proof.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SafetyState {
    Unverified,
    Verified,
    Changed,
}

impl AppData {
    /// Compare the stored fingerprint for `peer_id` with the current bundle.
    pub fn safety_state(&self, peer_id: i64, current: &str) -> SafetyState {
        match self.message_verified.get(&peer_id) {
            Some(stored) if stored == current => SafetyState::Verified,
            Some(_) => SafetyState::Changed,
            None => SafetyState::Unverified,
        }
    }
}

/// Local display timestamp for a message: `HH:MM` today, `YYYY-MM-DD HH:MM`
/// otherwise. An unparsable timestamp is returned unchanged.
pub fn format_message_time(iso: &str) -> String {
    let Ok(parsed) = chrono::DateTime::parse_from_rfc3339(iso) else {
        return iso.to_string();
    };
    let local = parsed.with_timezone(&chrono::Local);
    if local.date_naive() == chrono::Local::now().date_naive() {
        local.format("%H:%M").to_string()
    } else {
        local.format("%Y-%m-%d %H:%M").to_string()
    }
}

/// Total great-circle length of a `(lat, lon)` polyline in metres.
pub fn path_length_m(points: &[(f64, f64)]) -> f64 {
    points
        .windows(2)
        .map(|pair| haversine_m(pair[0].0, pair[0].1, pair[1].0, pair[1].1))
        .sum()
}

/// One-line measure readout shared by the native map HUD.
pub fn measure_label(points: &[(f64, f64)]) -> String {
    let count = points.len();
    format!(
        "Measure: {} · {count} {}",
        format_distance(path_length_m(points), true),
        if count == 1 { "point" } else { "points" }
    )
}

/// Age of a location timestamp: `just now`, `5m ago`, `2h ago`, `3d ago`.
/// Unparsable input returns `unknown`; a future timestamp (clock skew) clamps
/// to `just now` instead of showing a negative age.
pub fn format_age(iso: &str) -> String {
    let Ok(parsed) = chrono::DateTime::parse_from_rfc3339(iso) else {
        return "unknown".to_string();
    };
    let seconds = (chrono::Utc::now() - parsed.with_timezone(&chrono::Utc))
        .num_seconds()
        .max(0);
    let minutes = (seconds + 30) / 60;
    if minutes < 1 {
        "just now".to_string()
    } else if minutes < 60 {
        format!("{minutes}m ago")
    } else {
        let hours = (minutes + 30) / 60;
        if hours < 24 {
            format!("{hours}h ago")
        } else {
            format!("{}d ago", (hours + 12) / 24)
        }
    }
}

/// Upper bound on previous peer bundles kept per friend. Old bundles are
/// public keys only; the cap stops a peer that rotates constantly from growing
/// local storage without bound.
pub const MAX_CACHED_PEER_BUNDLES: usize = 8;

/// Append `bundle` to a peer cache unless it is already present. Returns
/// `true` when a new bundle was added. Newest is last so callers try it first.
pub fn cache_peer_bundle(
    cache: &mut Vec<MessagePublicBundle>,
    bundle: &MessagePublicBundle,
) -> bool {
    if cache.iter().any(|known| known == bundle) {
        return false;
    }
    cache.push(bundle.clone());
    if cache.len() > MAX_CACHED_PEER_BUNDLES {
        cache.remove(0);
    }
    true
}

